/**
 * Reposé Residence — floor explorer: residence hit-areas.
 *
 * One polygon per residence on each of the eight supplied floorplates, keyed
 * by the floorplate id used in `residences-map.json` and by the residence id
 * used in its residence set. Nothing else here: names, types, variants and
 * the unit-plan link all come from the package data at run time.
 *
 * Coordinates are PERCENTAGES OF THE FULL FLOORPLATE IMAGE — x across, y down —
 * so they hold at every size the sheet is shown at. The layer draws them in an
 * SVG whose viewBox is 0 0 100 100 stretched over the image, which is also how
 * to check or adjust one: open the plate, read a corner's position as a
 * percentage of the image, and edit the pair here.
 *
 * How the initial polygons were made
 * ----------------------------------
 * Derived once, offline, from the coloured residence fills the brochure prints
 * on each plate (blue / green / lilac for the 1-bed, 2-bed and 1-bed-study
 * residences of Levels 01–11; rose and salmon on 12–14; yellow, violet and
 * orange on 15), matched to each residence's `floorplatePosition` and then
 * checked against the type and variant labels printed inside every zone. The
 * two adjoining centre residences on the Levels 01–11 plates are divided along
 * the party wall between them. Production never samples pixels; this table is
 * the only source, and it is meant to be hand-tuned.
 *
 * Nothing about the drawings themselves is altered by any of this.
 */

/** [x, y] as a percentage of the floorplate image. */
export type Point = readonly [number, number]

export interface UnitHotspotConfig {
  /** Residence id from the plate's residence set in residences-map.json. */
  readonly residenceId: string
  /** Outline of the residence including its balcony, clockwise or not. */
  readonly polygon: readonly Point[]
  /**
   * Where to place the residence's tag, % of the image. Defaults to the
   * polygon's centroid; set it when a centroid lands somewhere awkward.
   */
  readonly labelAt?: Point
}

